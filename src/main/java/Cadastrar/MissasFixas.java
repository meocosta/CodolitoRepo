    // pega dias do mês a partir do primeiro dia
    public static int[] pegaDiasMes(int primeiroDia) {
        List<Integer> diasMes = new ArrayList<>();
        int dia = primeiroDia;
        while (dia <= 31) {
            diasMes.add(dia);
            dia += 7;
        }
        return diasMes.stream()
                .mapToInt(Integer::intValue)
                .toArray();
    }

    // cadastra missas fixas de quartas, sextas e sábados
    public static List<Missa> cadastrarMissas(String semana, int time, int[] dias) {
        List<Missa> missas = new ArrayList<>();
        for (int dia : dias) {
            Missa missa = new Missa(dia, semana, time, "-");
            missas.add(missa);
        }
        return missas;
    }

    // cadastra missas fixas dos domingos
    public static List<Missa> CadastrarDomingos(int[] dias) {
        List<Missa> missas = new ArrayList<>();
        for (int dia : dias) {
            if (dia == dias[0]) {
                Missa dom1 = new Missa(dia, "Domingo", 8, "-");
                Missa dom2 = new Missa(dia, "Domingo", 10, "Missa da Família");
                Missa dom3 = new Missa(dia, "Domingo", 18,
                        "Adoração ao Santíssimo Sacramento");
                missas.add(dom1);
                missas.add(dom2);
                missas.add(dom3);
                continue;
            }
            if (dia == dias[2]) {
                Missa dom1 = new Missa(dia, "Domingo", 8, "Missa do Dizimista");
                Missa dom2 = new Missa(dia, "Domingo", 10, "Missa do Dizimista");
                Missa dom3 = new Missa(dia, "Domingo", 18, "Missa do Dizimista");
                missas.add(dom1);
                missas.add(dom2);
                missas.add(dom3);
                continue;
            }
            if (dia == dias[3]) {
                Missa dom1 = new Missa(dia, "Domingo", 8, "-");
                Missa dom2 = new Missa(dia, "Domingo", 10, "Batismos");
                Missa dom3 = new Missa(dia, "Domingo", 18, "Missa Jovem");
                missas.add(dom1);
                missas.add(dom2);
                missas.add(dom3);
                continue;
            }
            Missa dom1 = new Missa(dia, "Domingo", 8, "-");
            Missa dom2 = new Missa(dia, "Domingo", 10, "-");
            Missa dom3 = new Missa(dia, "Domingo", 18, "-");
            missas.add(dom1);
            missas.add(dom2);
            missas.add(dom3);
        }
        return missas;
    }

    // apresenta na tabela as missas fixas cadastradas
    public void apresentaMissas(List<Missa> missas) {
        String[] colunas = { "dia", "semana", "hora", "celebrações" };
        List<String[]> lista = new ArrayList<>();

        for (Missa m : missas) {
            String[] linha = { String.valueOf(m.getDia()), m.getSemana(), String.valueOf(m.getTime()),
                    m.getCelebrações() };
            lista.add(linha);
        }

        String[][] dados = lista.toArray(new String[0][]);

        jTable1.setModel(
                new javax.swing.table.DefaultTableModel(
                        dados,
                        colunas));

    }

