    private void EnviarButtonActionPerformed(java.awt.event.ActionEvent evt) {// GEN-FIRST:event_EnviarButtonActionPerformed
        SalvarButton.setEnabled(true);
        int Domingo = Integer.parseInt(DomingoTXT.getText());
        int Quarta = Integer.parseInt(QuartaTXT.getText());
        int[] domingos = pegaDiasMes(Domingo);
        missasFixas.addAll(CadastrarDomingos(domingos));
        int[] quartas = pegaDiasMes(Quarta);
        missasFixas.addAll(cadastrarMissas("Quarta", 20, quartas));
        int[] sextas = pegaDiasMes(Quarta + 2);
        missasFixas.addAll(cadastrarMissas("Sexta", 15, sextas));
        int[] sabados = pegaDiasMes(Quarta + 3);
        missasFixas.addAll(cadastrarMissas("Sábado", 19, sabados));
        missasFixas.sort(Comparator.comparing(Missa::getDia));
        apresentaMissas(missasFixas);
    }// GEN-LAST:event_EnviarButtonActionPerformed

